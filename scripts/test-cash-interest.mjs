import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import vm from 'node:vm';
import ts from 'typescript';
async function load(file, imports={}) {
  const exports={};
  const js=ts.transpileModule(await readFile(new URL(`../${file}`,import.meta.url),'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
  vm.runInNewContext(js,{exports,Date,Intl,Map,Set,require:name=>{if(name in imports)return imports[name];throw new Error(name);}});
  return exports;
}
